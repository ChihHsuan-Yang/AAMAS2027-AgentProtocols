#!/usr/bin/env python3
"""Generate docs/PAPER_ARTIFACT_MAP.md: every figure and table -> its source.

WHY GENERATED.  A provenance table maintained by hand is the exact artifact
this project has repeatedly got wrong: a figure renamed, a table moved to the
supplement, a generator rewritten, and the index still describing the old
state.  Everything here is READ from the sources at generation time --
which documents include which figure, which tables each document inputs,
which canonical section each table parses, and the hashes of the files
actually on disk.  Nothing is asserted.

What is NOT derivable -- what scientific claim a figure supports, and which
rows it covers -- is declared below in PURPOSE, beside the code, so adding a
figure without saying what it is for is a visible omission rather than a
silent one.

Run:  python3 scripts/mk_artifact_map.py            # write
      python3 scripts/mk_artifact_map.py --check    # verify, write nothing
"""
import hashlib, json, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "docs", "PAPER_ARTIFACT_MAP.md")
DOCS = {"main paper": "paper/main.tex", "supplement": "paper/supplement.tex"}
SECTIONS = "paper/sections"

# The one thing a script cannot read off the sources: what a figure is FOR.
# Keyed by output stem. A figure the paper includes but that is missing here
# is reported as a gap, not skipped.
PURPOSE = {
    "fig1_v1_story": dict(
        claim="Roles do not buy the first answer; the gap opens after failure; "
              "both teams spend the same budget differently",
        script="analysis/scripts/mk_fig1_story.py",
        unit="panels A/B: trajectory, per (actor, condition). panel C: "
             "deliberation cycle, gemma-4 first-pass-wrong trajectories only",
        universe="Omni-MATH, all 3 actors; panel B recovery denominator = "
                 "trajectories whose FIRST evaluator verdict was incorrect",
        population="A/B marginal (each condition on its own denominator); "
                   "the paired form of panel B is in Figure 2",
        status="canonical"),
    "fig2_v2_xdomain": dict(
        claim="The same dissociation in a second, free-response science domain",
        script="analysis/scripts/mk_fig2_xdomain.py",
        unit="trajectory; bottom row counts PROBLEMS first-pass-wrong under "
             "both conditions",
        universe="gemma-4 only, both domains. gpt-oss's SciBench cell is "
                 "underpowered and deliberately not drawn",
        population="top row marginal, bottom row paired -- labelled in the figure",
        status="canonical"),
}

# Which canonical artifact each table's numbers come from, beyond the
# canonical-output section its own header names.
TABLE_DATA = {
    "scibench_replication": "experiments/results/xdomain/FROZEN_SCIBENCH/ "
                            "(2,296 rows) + experiments/results/FROZEN/",
    "single_agent_comparison": "EXTERNAL: a previously released trace corpus, "
                               "outside this repo -- see the caveat below",
}
DEFAULT_TABLE_DATA = "experiments/results/FROZEN/ (11,600 rows)"


def read(rel):
    p = os.path.join(ROOT, rel)
    return open(p, errors="ignore").read() if os.path.exists(p) else ""


def sha(rel):
    p = os.path.join(ROOT, rel)
    if not os.path.exists(p):
        return None
    return hashlib.sha256(open(p, "rb").read()).hexdigest()


def doc_sources():
    """Full text of each document, including the sections main.tex inputs."""
    secs = "".join(read(os.path.join(SECTIONS, f))
                   for f in sorted(os.listdir(os.path.join(ROOT, SECTIONS)))
                   if f.endswith(".tex"))
    return {"main paper": read(DOCS["main paper"]) + secs,
            "supplement": read(DOCS["supplement"])}


def main():
    src = doc_sources()

    # --- figures: which document includes which file -----------------------
    figs = {}
    for doc, text in src.items():
        for f in re.findall(r"\\includegraphics\[[^\]]*\]\{figures/([^}]+)\}", text):
            figs.setdefault(f, []).append(doc)

    # --- tables: which document inputs which file --------------------------
    tabs = {}
    for doc, text in src.items():
        for t in re.findall(r"\\input\{tables/([^}]+)\}", text):
            tabs.setdefault(t + ".tex", []).append(doc)

    gaps = []
    frz_p = os.path.join(ROOT, "FINAL_FREEZE.json")
    frz = json.load(open(frz_p)) if os.path.exists(frz_p) else {}

    L = ["# Paper artifact map — every figure and table, and where it came from",
         "",
         "**GENERATED by `scripts/mk_artifact_map.py`. Do not hand-edit.**",
         "Which document includes which figure, which tables each document",
         "inputs, and every hash below are read from the sources at generation",
         "time. Run `python3 scripts/mk_artifact_map.py --check` to detect drift.",
         "",
         "Back to [the project README](../README.md) · "
         "[manuscript package](../paper/README.md) · "
         "[current handoff](../HANDOFF_CURRENT.md)",
         "",
         "Design rationale for individual figures and tables — why this encoding,",
         "why no error bars, why one actor — lives in",
         "[`paper/figures/README.md`](../paper/figures/README.md) and",
         "[`paper/tables/README.md`](../paper/tables/README.md). This file is the",
         "cross-cutting provenance chain; those are the design records.",
         "",
         "## The chain every number travels",
         "",
         "```",
         "experiments/results/FROZEN/            Omni-MATH, 11,600 rows, sha256-manifested",
         "experiments/results/xdomain/FROZEN_SCIBENCH/   SciBench, 2,296 rows",
         "        |",
         "        v",
         "analysis/scripts/FINAL_TABLES.py       the ONLY source of a number",
         "        |-> analysis/out/FINAL_TABLES_OUTPUT.txt   (tables parse this)",
         "        `-> analysis/out/FIGDATA.json              (figures read this)",
         "        |",
         "        +-> analysis/scripts/mk_tables.py  -> paper/tables/*.tex",
         "        `-> analysis/scripts/mk_fig*.py    -> figures/ -> paper/figures/",
         "```",
         "",
         "No figure or table contains a hand-typed number. A value that cannot be",
         "produced by running `FINAL_TABLES.py` against the frozen snapshot is not",
         "a value this project reports.",
         "",
         "## Figures", ""]

    L += ["| Figure | Claim it supports | Output | Generator | Intermediate | Frozen data | Unit | Population | Status |",
          "|---|---|---|---|---|---|---|---|---|"]
    for f in sorted(figs):
        stem = f[:-4]
        p = PURPOSE.get(stem)
        if not p:
            gaps.append(f"figure {f} is included by {figs[f]} but has no "
                        f"PURPOSE entry in mk_artifact_map.py")
            continue
        n = "1" if stem.startswith("fig1") else "2"
        h = sha(f"paper/figures/{f}")
        L.append(
            f"| **{n}** ({', '.join(figs[f])}) | {p['claim']} | "
            f"`paper/figures/{f}`<br>sha256 `{h[:12]}…` | `{p['script']}` | "
            f"`analysis/out/FIGDATA.json` | `experiments/results/FROZEN/`"
            + (" + `…/FROZEN_SCIBENCH/`" if "xdomain" in stem else "")
            + f" | {p['unit']} | {p['population']} | {p['status']} |")

    # figures present in paper/figures/ but included by nothing
    shipped = {x for x in os.listdir(os.path.join(ROOT, "paper", "figures"))
               if x.endswith(".pdf")}
    for orphan in sorted(shipped - set(figs)):
        gaps.append(f"paper/figures/{orphan} ships but no document includes it")

    L += ["",
          "**Both figures draw from the same `FIGDATA.json`**, so they cannot "
          "disagree about a shared quantity. Figure 1B and Figure 2's "
          "Omni-MATH column show the *same cell* in different populations "
          "(marginal vs paired); each figure says which. They are different "
          "numbers and not a contradiction.",
          "",
          "## Tables", ""]

    L += ["| Table | Label | Purpose | Appears in | Output | Canonical input | Data universe | Status |",
          "|---|---|---|---|---|---|---|---|"]
    tdir = os.path.join(ROOT, "paper", "tables")
    for t in sorted(x for x in os.listdir(tdir) if x.endswith(".tex")):
        body = read(f"paper/tables/{t}")
        label = (re.search(r"\\label\{([^}]+)\}", body) or [None, "—"])[1]
        cin = (re.search(r"% canonical input\s*:\s*(.+)", body) or [None, "—"])[1].strip()
        cap = re.search(r"\\caption\{\\textbf\{([^.}]+)", body)
        purpose = cap.group(1).replace("\n", " ") if cap else "—"
        where = tabs.get(t)
        if not where:
            gaps.append(f"paper/tables/{t} is generated but no document inputs it")
            where_s, status = "**nothing — orphan**", "ORPHAN"
        else:
            where_s = ", ".join(where)
            status = "MAIN" if "main paper" in where else "SUPPLEMENT"
        L.append(f"| `{t}` | `{label}` | {purpose} | {where_s} | "
                 f"`paper/tables/{t}` | {cin} | "
                 f"{TABLE_DATA.get(t[:-4], DEFAULT_TABLE_DATA)} | {status} |")

    L += ["",
          "**Current `n` for every table is printed in the table itself**, per "
          "cell, with its denominator named. This file deliberately does not "
          "restate those counts: a count copied here would be a second copy of "
          "a number, which is the defect `SOURCE_OF_TRUTH.md` exists to "
          "prevent.",
          "",
          "### The one table whose data is not ours",
          "",
          "`single_agent_comparison.tex` reads a **previously released trace "
          "corpus that lives outside this repository** "
          "(`[T17] … NOT IN THE FROZEN SNAPSHOT` in the canonical output names "
          "the path and hashes the file). Two consequences, both stated in the "
          "paper: its two actor arms were built from *different source "
          "commits*, so each within-actor direction is a sound guard and the "
          "**gap between actors is not**; and if that sibling project moves, "
          "`FINAL_TABLES.py` prints `UNAVAILABLE:` for T17 rather than "
          "silently dropping it.",
          ""]

    if frz.get("gates"):
        g = frz["gates"]
        L += ["## Build state at last freeze", "",
              f"| | |", "|---|---|",
              f"| freeze record | `FINAL_FREEZE.json`, {frz.get('frozen_at','—')} |",
              f"| GitHub HEAD then | `{frz.get('github_head','—')[:12]}` |",
              f"| main paper | {g.get('main_pages','—')} pages, main text ends p8 |",
              f"| supplement | {g.get('supp_pages','—')} pages, no limit |",
              f"| main text sha256 | `{(frz.get('main_text_sha256') or '')[:24]}…` |",
              f"| supplement text sha256 | `{(frz.get('supplement_text_sha256') or '')[:24]}…` |",
              f"| all gates | **{'PASS' if frz.get('ALL_GATES_PASS') else 'FAIL: ' + str(frz.get('FAILED_GATES'))}** |",
              "",
              "Text hashes, not byte hashes: pdflatex embeds a wall-clock "
              "timestamp, so a PDF's byte hash identifies a *build*. "
              "`pdftotext x.pdf - | shasum -a 256` reproduces the values above.",
              ""]

    L += ["## Regenerating any of it", "",
          "```bash",
          "python3 analysis/scripts/FINAL_TABLES.py > analysis/out/FINAL_TABLES_OUTPUT.txt",
          "python3 analysis/scripts/mk_tables.py        # -> paper/tables/*.tex",
          "python3 analysis/scripts/mk_fig1_story.py    # -> figures/ and paper/figures/",
          "python3 analysis/scripts/mk_fig2_xdomain.py",
          "python3 scripts/mk_artifact_map.py           # -> this file",
          "python3 scripts/final_freeze.py              # every gate, both documents",
          "```",
          "",
          "The figure generators now copy into `paper/figures/` themselves. "
          "Figure PDFs are byte-reproducible (the wall-clock `CreationDate` is "
          "stripped), so a changed figure hash means changed *data*.",
          ""]

    if gaps:
        L += ["## GAPS — resolve these", ""] + [f"- {x}" for x in gaps] + [""]
    else:
        L += ["## Gaps", "",
              "None. Every figure the documents include has a declared purpose, "
              "every generated table is inputted by a document, and no file in "
              "`paper/figures/` is unreferenced.", ""]

    txt = "\n".join(L)
    if "--check" in sys.argv:
        cur = open(OUT).read() if os.path.exists(OUT) else None
        if cur != txt:
            print("STALE: docs/PAPER_ARTIFACT_MAP.md does not match its sources."
                  " Run: python3 scripts/mk_artifact_map.py")
            return 1
        print("CHECK OK: artifact map matches the sources")
        return 0 if not gaps else 1
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write(txt)
    print(f"wrote docs/PAPER_ARTIFACT_MAP.md  "
          f"({len(figs)} figures, {len(tabs)} tables inputted)")
    if gaps:
        print("GAPS:")
        for x in gaps:
            print("  " + x)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
