#!/usr/bin/env python3
"""Verify every repo-relative path and markdown link in the documentation.

WHY.  A navigation document whose links do not resolve is worse than no
document: it sends a new collaborator to a path that does not exist and
costs them the time it was meant to save. This project has had a README
naming a dead canonical path before.

WHAT IT CHECKS, in the files that are meant to be navigation:
  * every markdown link target that is a repo-relative path -- these are
    navigation promises and must resolve
  * every `backtick path` CONTAINING A SLASH -- a directory-qualified path
    is a claim about where something is

WHAT IT DELIBERATELY DOES NOT CHECK, and why.  A first version flagged 88
references of which exactly one was real.  Bare basenames in prose --
`main.tex`, `FINAL_TABLES.py`, `MANIFEST.json` -- are not path claims; they
name a file the surrounding sentence has already located, and demanding
they resolve from the repo root produces noise that buries the one real
failure.  A check with an 87/88 false-positive rate is a check nobody runs.
Bare basenames are instead resolved anywhere in the repo, and reported only
if the name exists NOWHERE -- which catches the case that actually matters,
a file that was renamed or deleted.

IT CHECKS AGAINST GIT, NOT THE WORKING COPY.  Found 2026-10-02 by cloning:
this script passed in the working copy and FAILED in a fresh clone, because
five documented paths are gitignored -- they exist on this laptop and not
for anybody else. A link check that only ever runs where the files happen
to be present cannot detect the failure it exists to detect. So a path must
be tracked by git, and a path that exists locally but is gitignored is
reported as UNTRACKED, with its own exit status: it is not a typo, it is a
promise a clone cannot keep, and the fix is usually a sentence saying the
file is local-only, not a corrected path.

It does NOT check external URLs -- it cannot, and a network check that
fails on a proxy would report a false broken link. Those are listed
separately as UNVERIFIED, which is the honest state.
"""
import os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCS = ["README.md", "HANDOFF_CURRENT.md", "SUBMISSION_PACKAGE.md",
        "SUBMISSION_CHECKLIST.md", "TODO.md", "paper/README.md",
        "paper/figures/README.md", "paper/tables/README.md",
        "docs/PAPER_ARTIFACT_MAP.md", "docs/DATA_PROVENANCE.md",
        "docs/TRACE_AVAILABILITY.md", "docs/REPRODUCIBILITY.md",
        "docs/INVALID_AND_SUPERSEDED.md"]

# Paths that are DELIBERATELY not in git, with the reason. A documented
# path on this list is fine; one that is NOT on it and is missing from a
# clone fails, which is the point -- a new untracked path is almost always
# an accident, and the four below are not.
#
# Keyed by basename as well as full path, because prose names both.
LOCAL_ONLY = {
    "experiments/results/FROZEN/": "283 MB of raw trajectories; GitHub rejects >100 MB. In the private HF repo, bytes verified identical",
    "experiments/results/xdomain/FROZEN_SCIBENCH/": "same",
    "hf_artifact/raw/": "the HF upload staging copy of those same traces",
    "experiments/results/main/campaign_v1_TRUNCATION_BUG.jsonl": "a quarantined run, retained locally as evidence and never released",
    "experiments/results/smoke/smoke_v1_prefix_PREFIX_BUG.jsonl": "the same",
    "campaign_v2.jsonl": "raw trace, see above",
    "actor3.jsonl": "raw trace, see above",
    "armCp.jsonl": "raw trace, see above",
    "scibench_AB.jsonl": "raw trace, see above",
    "main.pdf": "a build product; regenerated by pdflatex, never committed",
    "supplement.pdf": "the same",
    "paper/main.pdf": "a build product; regenerated by pdflatex, never committed",
    "paper/supplement.pdf": "the same",
    "tables/": "paper/tables/ written without its prefix inside a code block that already cd's into paper/",
}

LINK = re.compile(r"\[[^\]]*\]\(([^)\s]+)\)")
CODE = re.compile(r"`([^`\n]+)`")
EXTS = (".md", ".py", ".tex", ".json", ".jsonl", ".bib", ".cls", ".bst",
        ".pdf", ".txt", ".parquet", ".sty")


def is_qualified_path(s):
    """A directory-qualified path -- a claim about WHERE something is.

    `hf:` marks a path inside the Hugging Face artifact repository, which
    is a different file tree. Those are real claims but not claims about
    THIS repo, so they are excluded here rather than silently passed --
    the prefix is what makes the distinction visible to a reader too.
    """
    s = s.strip()
    if s.startswith("hf:"):
        return False
    if not s or " " in s or s.startswith(("http", "#", "$", "-", "@")):
        return False
    if "*" in s or "{" in s or "\u2026" in s:      # glob, brace set, ellipsis
        return False
    return "/" in s and (s.endswith("/") or s.endswith(EXTS))


def is_basename(s):
    """A bare filename, which is a weaker claim: that the file EXISTS."""
    s = s.strip()
    return (s and " " not in s and "/" not in s and "*" not in s
            and s.endswith(EXTS) and not s.startswith("."))


_TRACKED = None
def tracked():
    """Every path git actually has. The clone's view, not the laptop's."""
    global _TRACKED
    if _TRACKED is None:
        out = subprocess.run(["git", "-C", ROOT, "ls-files"],
                             capture_output=True, text=True)
        if out.returncode != 0:
            raise SystemExit("ABORT: `git ls-files` failed. Refusing to fall "
                             "back to the working copy -- that fallback is "
                             "the defect this check exists to catch.")
        _TRACKED = set(out.stdout.splitlines())
        if not _TRACKED:
            raise SystemExit("ABORT: git tracks no files. An empty sweep is "
                             "not a pass.")
    return _TRACKED


def in_git(path):
    """Tracked as a file, or a directory containing tracked files."""
    p = path.rstrip("/")
    return p in tracked() or any(t.startswith(p + "/") for t in tracked())


_ALL = None
def exists_anywhere(name):
    """A bare basename, resolved against git's file list."""
    global _ALL
    if _ALL is None:
        _ALL = {os.path.basename(t) for t in tracked()}
    return name in _ALL


def main():
    broken, untracked, external, checked = [], [], set(), 0
    for doc in DOCS:
        dp = os.path.join(ROOT, doc)
        if not os.path.exists(dp):
            broken.append((doc, "<the document itself>", "document missing"))
            continue
        base = os.path.dirname(dp)
        text = open(dp, errors="ignore").read()

        for tgt in LINK.findall(text):
            if tgt.startswith(("http://", "https://")):
                external.add(tgt)
                continue
            if tgt.startswith("#"):
                continue                      # same-page anchor
            path = tgt.split("#")[0]
            checked += 1
            rel = os.path.relpath(os.path.join(base, path), ROOT)
            if in_git(rel):
                continue
            if path in LOCAL_ONLY or os.path.exists(os.path.join(base, path)):
                untracked.append((doc, tgt))
            else:
                broken.append((doc, tgt, "link target does not exist"))

        for c in CODE.findall(text):
            if is_qualified_path(c):
                checked += 1
                # Resolve against the repo root AND the document's own
                # directory -- both spellings appear legitimately.
                rels = [c, os.path.relpath(os.path.join(base, c), ROOT)]
                if any(in_git(r) for r in rels):
                    continue
                if any(os.path.exists(os.path.join(ROOT, r)) for r in rels):
                    untracked.append((doc, c))
                else:
                    broken.append((doc, c, "qualified path does not exist"))
            elif is_basename(c):
                checked += 1
                if exists_anywhere(c):
                    continue
                if c in LOCAL_ONLY:
                    untracked.append((doc, c))
                else:
                    broken.append((doc, c, "no file of this name is tracked "
                                           "anywhere in the repo"))

    nhf = sum(open(os.path.join(ROOT, d), errors="ignore").read().count("`hf:")
              for d in DOCS if os.path.exists(os.path.join(ROOT, d)))
    print(f"checked {checked} repo-relative references across "
          f"{len(DOCS)} documents")
    if nhf:
        print(f"  ({nhf} `hf:` references point into the Hugging Face "
              f"artifact repo -- a different tree, not checked here)")
    if external:
        print(f"\n{len(external)} external URLs NOT checked (no network "
              f"verification; reporting them as unverified rather than "
              f"claiming they resolve):")
        for u in sorted(external):
            print(f"    {u}")
    unexpected = [(d, t) for d, t in untracked if t not in LOCAL_ONLY]
    expected = [(d, t) for d, t in untracked if t in LOCAL_ONLY]
    if expected:
        print(f"\n{len(expected)} references to KNOWN local-only paths "
              f"(declared in LOCAL_ONLY with a reason -- not in a clone, and "
              f"the documents say so):")
        for doc, tgt in sorted(set(expected)):
            print(f"    {doc}: {tgt}  -- {LOCAL_ONLY[tgt]}")
    if unexpected:
        print(f"\n{len(unexpected)} UNTRACKED and UNDECLARED -- present on "
              f"this machine, absent from a clone, and not on the LOCAL_ONLY "
              f"list. Either commit it, or declare it local-only with a "
              f"reason:")
        for doc, tgt in unexpected:
            print(f"    {doc}: {tgt!r}")
    if broken:
        print(f"\n{len(broken)} BROKEN:")
        for doc, tgt, why in broken:
            print(f"    {doc}: {tgt!r} -- {why}")
    if broken or unexpected:
        return 1
    print("\nAll repo-relative references resolve in a CLONE, not merely "
          "on this machine.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
