#!/usr/bin/env python3
"""Supplement table: the forced-submission run (role-structured prompts, every
cycle submitted) against the gated role-structured team and the role-free team
with feedback, on the same 400 Omni-MATH problems (gemma-4; Llama-3.3 once
its run exists).

Reads analysis/out/FIGDATA_GATE.json (bf_gate.py, block [G5]) and writes
paper/tables/forced_submission.tex (and forced_submission_llama33.tex when
FIGDATA_GATE.json has the Llama-3.3 rows).  No number is typed by hand.
"""
import json
import math
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
GATE = sys.argv[sys.argv.index("--gate") + 1] if "--gate" in sys.argv else \
    os.path.join(ROOT, "analysis", "out", "FIGDATA_GATE.json")
DST = sys.argv[sys.argv.index("--out") + 1] if "--out" in sys.argv else \
    os.path.join(ROOT, "paper", "tables", "forced_submission.tex")
G = json.load(open(GATE))

ROWS = [("Afs (forced submission)", "role-structured, every cycle submitted"),
        ("A re-run after the freeze (bridge)", "role-structured, re-run after the freeze"),
        ("A frozen", "role-structured, frozen snapshot"),
        ("Bf (role-free with feedback)", "role-free with feedback")]
PAIRS = [("Afs vs A re-run (bridge)", "every cycle submitted vs.\\ re-run"),
         ("Afs vs Bf", "every cycle submitted vs.\\ role-free with feedback"),
         ("A re-run (bridge) vs Bf", "re-run vs.\\ role-free with feedback")]


def pv(p):
    if p >= 0.001:
        return "${:.2g}$".format(p)
    e = int(math.floor(math.log10(p)))
    m = round(p / 10 ** e, 1)
    if m >= 10:
        m, e = m / 10, e + 1
    return "${:.1f}{{\\times}}10^{{{}}}$".format(m, e)


from decimal import Decimal, ROUND_HALF_UP


def r(x, q="0.001"):
    """Round half-up from the shortest decimal repr: 307/400 = 0.7675 -> 0.768
    (plain '{:.3f}' gives 0.767 for this value and 0.818 for 0.8175)."""
    return str(Decimal(repr(x)).quantize(Decimal(q), rounding=ROUND_HALF_UP))


def build(pfx, actor_label, label, rows_, pairs_):
    ns = {G[pfx + "|" + k]["n"] for k, _ in rows_}
    assert len(ns) == 1, ("the rows must cover the same problems", ns)
    n = ns.pop()
    body = []
    for key, lab in rows_:
        d = G[pfx + "|" + key]
        body.append(" & ".join([
            lab,
            "${}$".format(r(d["firstpass"])),
            "${}/{}={}$".format(d["recovered"], d["n_fpw"], r(d["recovery"])),
            "${}$".format(r(d["final"])),
            "${}$".format(r(d["verdicts"], "0.01")),
            "${}$".format(r(d["approvals"], "0.01")),
        ]) + r" \\")
    pair = []
    for key, lab in pairs_:
        rr = G[pfx + "_paired|rec|" + key]
        f = G[pfx + "_paired|final|" + key]
        pair.append(" & ".join([
            lab,
            "${}$".format(rr["n"]), "${}$ / ${}$".format(rr["first_only"], rr["second_only"]), pv(rr["p"]),
            "${}$ / ${}$".format(f["first_only"], f["second_only"]), pv(f["p"]),
        ]) + r" \\")
    return r"""%% GENERATED by analysis/scripts/mk_afs_table.py from FIGDATA_GATE.json
%% (bf_gate.py [G5]) -- do not edit by hand.
\begin{table*}[t]
\centering
\caption{\textbf{Removing the submission gate""" + ("" if pfx == "afs" else ", " + actor_label) + r""".} """ + actor_label + r""", Omni-MATH, the
same """ + "${}$".format(n) + r""" problems in every row. The forced-submission run uses the
role-structured prompts byte for byte; the pipeline submits the team's answer
to the evaluator in every cycle, whatever the Reviewer decides. Recovery is
over each row's own first-pass-wrong trajectories; verdicts and Reviewer
approvals are per first-pass-wrong trajectory and include the first. In the
forced-submission run approvals are logged but do not decide submission. The
lower block pairs the conditions on the problems both first answer wrongly
(recovery) and on all problems (final accuracy): problems solved only by the
first condition / only by the second, exact McNemar $p$.}
\label{""" + label + r"""}
\footnotesize
\begin{tabular}{@{}l ccccc@{}}
\toprule
condition & first pass & recovery & final accuracy & verdicts & Reviewer approvals \\
\midrule
""" + "\n".join(body) + r"""
\bottomrule
\end{tabular}

\vspace{4pt}
\begin{tabular}{@{}l ccc cc@{}}
\toprule
 & \multicolumn{3}{c}{recovery (both first wrong)} & \multicolumn{2}{c}{final accuracy} \\
\cmidrule(lr){2-4}\cmidrule(lr){5-6}
pair & $n$ & first / second only & $p$ & first / second only & $p$ \\
\midrule
""" + "\n".join(pair) + r"""
\bottomrule
\end{tabular}
\end{table*}
"""


open(DST, "w").write(build("afs", "gemma-4", "tab:forced", ROWS, PAIRS))
print("wrote", DST)

# Llama-3.3 (exploratory, post-freeze), written only once bf_gate.py [G5] has its rows.
L = "afs_llama33"
if L + "|Afs (forced submission)" in G:
    rows_l = [(k, lab) for k, lab in ROWS if L + "|" + k in G]
    pairs_l = [(k, lab) for k, lab in PAIRS + [("Afs vs A frozen", "every cycle submitted vs.\\ frozen")]
               if L + "_paired|rec|" + k in G]
    order = ["Afs vs A re-run (bridge)", "Afs vs A frozen", "Afs vs Bf", "A re-run (bridge) vs Bf"]
    pairs_l.sort(key=lambda kl: order.index(kl[0]))
    dst_l = DST.replace("forced_submission.tex", "forced_submission_llama33.tex")
    open(dst_l, "w").write(build(L, "Llama-3.3", "tab:forced_llama", rows_l, pairs_l))
    print("wrote", dst_l)
