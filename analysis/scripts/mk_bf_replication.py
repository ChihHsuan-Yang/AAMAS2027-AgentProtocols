#!/usr/bin/env python3
"""Supplement table: the two independent runs of the gemma-4 feedback-matched
cells, side by side, against the frozen role-structured cell.

Reads analysis/out/FIGDATA_BF.json (run 1, reported in the main text) and
analysis/out/FIGDATA_BF_chain2.json (run 2), both written by bf_numbers.py
with identical definitions. Writes paper/tables/bf_replication.tex.
No number in this file is typed by hand.

Run:  python3 analysis/scripts/mk_bf_replication.py
"""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "analysis", "out")
R1 = json.load(open(os.path.join(OUT, "FIGDATA_BF.json")))
R2 = json.load(open(os.path.join(OUT, "FIGDATA_BF_chain2.json")))
ACT = "gemma-4-31B-it"
DOM = [("omni", "Omni-MATH"), ("scibench", "SciBench")]


def p(x):
    """Exact McNemar p: two significant figures, scientific below 0.001."""
    if x < 1e-3:
        m, e = "{:.1e}".format(x).split("e")
        return "$p={}\\times10^{{{}}}$".format(m, int(e))
    return "$p={:.2g}$".format(x)


rows = []
for dk, dn in DOM:
    k = "{}|{}|".format(dk, ACT)
    a = R1["cells"][k + "A"]
    rows.append("\\multicolumn{6}{@{}l}{\\emph{%s}} \\\\" % dn)
    rows.append("\\quad role-structured (frozen) & ${:.3f}$ & ${}/{}={:.3f}$ & -- & ${:.3f}$ & -- \\\\".format(
        a["firstpass"], a["decomp"]["recovered"], a["n_fpw"], a["recovery"], a["final_prereg"]))
    for lab, R in (("role-free + feedback, run 1", R1), ("role-free + feedback, run 2", R2)):
        c = R["cells"][k + "Bf"]
        pr = R["paired_recovery"][k + "A-Bf"]
        pf = R["paired_final"][k + "A-Bf"]
        rows.append("\\quad {} & ${:.3f}$ & ${}/{}={:.3f}$ & ${}$ vs ${}$, {} & ${:.3f}$ & ${}$ vs ${}$, {} \\\\".format(
            lab, c["firstpass"], c["decomp"]["recovered"], c["n_fpw"], c["recovery"],
            pr["y_only"], pr["x_only"], p(pr["p"]), c["final_prereg"], pf["y_only"], pf["x_only"], p(pf["p"])))
    rows.append("\\addlinespace")

files = {k: v["sha256"][:12] for k, v in R2["provenance"]["files"].items() if v.get("role") == "Bf"}
tex = r"""%% GENERATED by analysis/scripts/mk_bf_replication.py from FIGDATA_BF.json and
%% FIGDATA_BF_chain2.json -- do not edit by hand.
\begin{table*}[t]
\centering
\caption{\textbf{The gemma-4 feedback-matched cells, run twice.}
Role-structured: Planner, Executor and Reviewer prompts (the frozen run).
Role-free + feedback: one generic prompt for all three agents, with the
evaluator's verdict and repair hint shown; both runs use byte-identical
runner and prompt code, and the main text reports run 1. \emph{First
pass}: whether a trajectory's (one problem's run) first submitted answer is
correct. \emph{Recovery}: first-pass-wrong trajectories that finish
correct, over each condition's own first-pass-wrong set (count /
denominator). \emph{Final}: accuracy at the end over all problems,
never-graded trajectories counted as incorrect. The \emph{paired} columns
compare each role-free run with the role-structured run on problems
first-pass wrong under both (recovery) or on all problems (final): problems
recovered, or finally correct, only without roles versus only with them,
with the exact McNemar $p$ for the two counts.}
\label{tab:bfreplication}
\small
\begin{tabular}{@{}lccccc@{}}
\toprule
 & first pass & recovery & paired recovery & final & paired final \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}
\end{table*}
"""
dst = os.path.join(ROOT, "paper", "tables", "bf_replication.tex")
open(dst, "w").write(tex)
print("wrote", dst)
