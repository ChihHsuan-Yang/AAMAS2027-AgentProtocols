#!/usr/bin/env python3
"""Supplement table: robustness of the verdict-matched recovery contrast.

Reads analysis/out/FIGDATA_GATE.json (bf_gate.py, blocks [G4] and [G6]) and
writes paper/tables/verdict_robustness.tex.  No number is typed by hand.
"""
import json
import os
from decimal import Decimal, ROUND_HALF_UP

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
G = json.load(open(os.path.join(ROOT, "analysis", "out", "FIGDATA_GATE.json")))

CELLS = [("omni|gemma-4-31B-it", "gemma-4, Omni-MATH"),
         ("omni|gpt-oss-120b", "gpt-oss, Omni-MATH"),
         ("omni|Llama-3.3-70B-Instruct", "Llama-3.3, Omni-MATH"),
         ("scibench|gemma-4-31B-it", "gemma-4, SciBench"),
         ("scibench|gpt-oss-120b", "gpt-oss, SciBench")]
VARIANTS = [("main", "as in Table~2"),
            ("informative", "role-structured team received $\\geq2$ verdicts"),
            ("symmetric", "both cut at the smaller verdict count"),
            ("symmetric_informative", "both cut, $\\geq2$ verdicts"),
            ("recoded", "scoring defect recoded"),
            ("recoded_informative", "recoded, $\\geq2$ verdicts")]


def r3(x):
    s = str(Decimal(repr(x)).quantize(Decimal("0.001"), rounding=ROUND_HALF_UP))
    return ("+" if x >= 0 and not s.startswith("-") else "") + s.replace("-", "{-}")


def cell(d):
    return "${}$ {{\\footnotesize $[{},\\,{}]$}}".format(r3(d["diff"]), r3(d["ci95"][0]), r3(d["ci95"][1]))


ties = []
for key, name in CELLS:
    t = G["verdict_robust_ties|" + key]
    ties.append("{} & ${}$ & ${}$ & ${}$ & ${}$ & ${}$ / ${}$ \\\\".format(
        name, t["n"], t["forced_ties"], t["never_submitted"], t["informative"], t["recodes_A"], t["recodes_Bf"]))

rows = []
for v, label in VARIANTS:
    # the "as in Table 2" row reproduces the main paper's pooled estimate ([G4]) exactly
    a = (dict(G["verdict_matched_pooled"]) if v == "main"
         else G["verdict_robust_pooled|{}|all".format(v)])
    b = G["verdict_robust_pooled|{}|noLlama".format(v)]
    rows.append("{} & ${}$ & {} & {} & ${}$ & {} \\\\".format(
        label, a["n"], cell(a), "yes" if a["equivalent"] else "no", b["n"], cell(b)))

haz = []
for k in (2, 3, 4):
    h = G.get("verdict_hazard|pooled|{}".format(k))
    if not h:
        continue
    (na, da), (nf, df) = h["A"], h["Bf"]
    haz.append("verdict {} & ${}/{}={}$ & ${}/{}={}$ \\\\".format(
        k, na, da, r3(na / da).lstrip("+") if da else "--", nf, df, r3(nf / df).lstrip("+") if df else "--"))

TEX = r"""%% GENERATED by analysis/scripts/mk_robust_table.py from FIGDATA_GATE.json
%% (bf_gate.py [G4], [G6]) -- do not edit by hand.
\begin{table*}[t]
\centering
\caption{\textbf{Robustness of the verdict-matched recovery contrast.} RS:
role-structured (Planner, Executor and Reviewer prompts); RF: role-free
(one generic prompt for all three agents) with the evaluator's feedback
shown; a cell is one actor (the model playing all three agents) on one
benchmark. The contrast takes the problems both teams first answer wrongly
and cuts the RF trajectory (one problem's run) after as many evaluator
verdicts (PASS or FAIL decisions) as the RS trajectory received on that
problem, then compares recovery (finishing correct). Where RS received a
single verdict (it never submitted again, or submitted once and stopped),
the cut RF trajectory cannot recover either, so the pair ties at zero by
construction. \emph{Upper block}: such forced ties per cell, how many of
them never submitted, the problems left, and the trajectories whose held
answer matched the key but were graded wrong (the scoring defect of the
main paper's Limitations). \emph{Middle block}: the pooled difference (RS
minus RF, stratified by cell, $95\%$ bootstrap confidence interval
resampling problems) under six definitions, with and without Llama-3.3;
\emph{equivalent} means the $90\%$ interval lies inside $\pm0.05$. Recoding
counts an RS trajectory with a correct held answer as recovered, and an RF
one only if it was not cut. \emph{Lower block}: per-verdict pass rates, the
share of trajectories whose $k$-th verdict is PASS among those whose
earlier verdicts all failed, pooled over the five cells.}
\label{tab:robust}
\footnotesize
\begin{tabular}{@{}l ccccc@{}}
\toprule
cell & paired $n$ & forced ties & never submitted & left & held-answer recodes (RS / RF) \\
\midrule
""" + "\n".join(ties) + r"""
\bottomrule
\end{tabular}

\vspace{4pt}
\begin{tabular}{@{}l c l c c l@{}}
\toprule
 & \multicolumn{3}{c}{all five cells} & \multicolumn{2}{c}{without Llama-3.3} \\
\cmidrule(lr){2-4}\cmidrule(lr){5-6}
definition & $n$ & difference [95\% CI] & equivalent & $n$ & difference [95\% CI] \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}

\vspace{4pt}
\begin{tabular}{@{}l cc@{}}
\toprule
per-verdict pass rate & role-structured & role-free with feedback \\
\midrule
""" + "\n".join(haz) + r"""
\bottomrule
\end{tabular}
\end{table*}
"""
dst = os.path.join(ROOT, "paper", "tables", "verdict_robustness.tex")
open(dst, "w").write(TEX)
print("wrote", dst)
