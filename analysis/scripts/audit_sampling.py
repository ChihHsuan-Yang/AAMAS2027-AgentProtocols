"""AUDIT: is the seeded 1,600-problem OmniMath2 sample representative of the
full 4,181 matched pool?  And what exactly are SciBench's denominators?

Reproducible: reads only the released problems parquet and re-derives the
sample through `runner.load_problems`, the same function the campaign used.
Writes analysis/out/SAMPLING_AUDIT.md and a PNG.

Run:  python3 analysis/scripts/audit_sampling.py
"""
import sys, os, json, collections
import numpy as np, pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, "experiments"))
import runner  # noqa: E402

OUT = os.path.join(ROOT, "analysis", "out")
os.makedirs(OUT, exist_ok=True)
L = []
def w(s=""): L.append(s); print(s)

df = pd.read_parquet(runner.PROBLEMS_PARQUET)

# ---------------------------------------------------------------- OmniMath2
om = df[df.benchmark_id == "omnimath2"].copy()
SEED, N = 20270101, 1600
sel_ids = {p["problem_uid"] for p in runner.load_problems(N, SEED)}
om["selected"] = om.problem_uid.astype(str).isin(sel_ids)

w("# Sampling and denominator audit")
w()
w("Generated by `analysis/scripts/audit_sampling.py`. Every figure below is")
w("re-derived from the released problems parquet; the sample is re-drawn")
w("through `runner.load_problems`, the same function the campaign used.")
w()
w("## 1. OmniMath2: 4,181 available -> 1,600 run")
w()
w(f"- full matched pool: **{len(om)}**")
w(f"- scientific run: **{om.selected.sum()}** ({om.selected.mean():.1%})")
w(f"- seed: **{SEED}**, drawn by `runner.load_problems(n=1600, seed={SEED})`")
w(f"- manifest: `experiments/manifest_omnimath2_n1600.json`")
w()
w("**Procedure** (verbatim from `runner.py:load_problems`): filter to the")
w("benchmark, require `problem_text` and `answer` non-null, sort by")
w("`problem_uid` with a stable mergesort, shuffle the index with")
w("`random.Random(seed)`, take the first n, re-sort. Deterministic and")
w("independent of row order in the parquet.")
w()
w("**It is a uniform random sample of the whole pool — not a tier-specific,")
w("difficulty-stratified, or otherwise purposive subset.**")
w()

# Tier metadata
w("## 2. Is difficulty/tier metadata available?")
w()
for c in ("difficulty_tier", "question_type", "difficulty_score", "subset"):
    if c in om.columns:
        nn = int(om[c].notna().sum())
        w(f"- `{c}`: non-null **{nn}/{len(om)}**, distinct {om[c].nunique()}")
w()
w("`difficulty_tier` and `question_type` are **entirely null** for this")
w("benchmark, so no tier table is possible on those fields. `difficulty_score`")
w("is fully populated and is used below as the difficulty axis.")
w()

# Representativeness
w("## 3. Representativeness: full 4,181 vs selected 1,600")
w()
full, sel = om.difficulty_score.astype(float), om[om.selected].difficulty_score.astype(float)
w("### 3a. difficulty_score")
w()
w("| statistic | full 4,181 | selected 1,600 | delta |")
w("|---|---:|---:|---:|")
for lab, fn in (("mean", np.mean), ("std", np.std), ("min", np.min),
                ("25th pct", lambda x: np.percentile(x, 25)),
                ("median", np.median),
                ("75th pct", lambda x: np.percentile(x, 75)), ("max", np.max)):
    a, b = fn(full), fn(sel)
    w(f"| {lab} | {a:.4f} | {b:.4f} | {b-a:+.4f} |")
w()
try:
    from scipy.stats import ks_2samp, chi2_contingency
    ks = ks_2samp(full, sel)
    w(f"Two-sample Kolmogorov-Smirnov: **D={ks.statistic:.4f}, p={ks.pvalue:.3f}**")
    w("(a large p means the selected sample is *not* distinguishable from the pool)")
except ImportError:
    w("_scipy unavailable; KS test skipped_")
w()

w("### 3b. difficulty_score, binned")
w()
w("| score | full 4,181 | share | selected 1,600 | share | delta |")
w("|---|---:|---:|---:|---:|---:|")
vc_f = om.difficulty_score.value_counts().sort_index()
vc_s = om[om.selected].difficulty_score.value_counts().sort_index()
for k in vc_f.index:
    f_n = int(vc_f.get(k, 0)); s_n = int(vc_s.get(k, 0))
    w(f"| {k} | {f_n} | {f_n/len(om):.3f} | {s_n} | {s_n/1600:.3f} | "
      f"{s_n/1600 - f_n/len(om):+.3f} |")
w()

w("### 3c. subset (source competition)")
w()
w("| subset | full | share | selected | share | delta |")
w("|---|---:|---:|---:|---:|---:|")
sf = om.subset.value_counts(); ss = om[om.selected].subset.value_counts()
for k in sf.head(15).index:
    f_n = int(sf.get(k, 0)); s_n = int(ss.get(k, 0))
    w(f"| {k} | {f_n} | {f_n/len(om):.3f} | {s_n} | {s_n/1600:.3f} | "
      f"{s_n/1600 - f_n/len(om):+.3f} |")
w(f"\n_(top 15 of {om.subset.nunique()} subsets)_")
w()
try:
    tab = pd.crosstab(om.subset, om.selected)
    tab = tab[(tab.sum(axis=1) >= 5)]
    chi2, p, dof, _ = chi2_contingency(tab.values)
    w(f"Chi-square on subset x selected: **chi2={chi2:.1f}, dof={dof}, p={p:.3f}**")
except Exception as e:
    w(f"_chi-square skipped: {type(e).__name__}_")
w()

# ---------------------------------------------------------------- SciBench
w("## 4. SciBench denominators: 692 upstream -> 580 released -> 574 matched")
w()
sb = df[df.benchmark_id == "scibench"].copy()
has_slice = sb.available_slices_json.apply(lambda s: "text_only" in json.loads(s))
w(f"- upstream SciBench (published): **692**")
w(f"- present in the released problems table: **{len(sb)}**")
w(f"- carrying the `text_only` slice, i.e. the matched scientific run: **{int(has_slice.sum())}**")
w(f"- **run in this campaign: 574 problems x 2 actors x 2 arms = 2,296 trajectories**")
w()
w("### Where the 692 - 580 = 112 go")
w()
w("**NOT RECOVERABLE FROM THIS RELEASE, and I will not guess.** The released")
w("problems table contains only rows that survived the upstream build, so the")
w("112 excluded items are absent from it entirely and carry no reason code")
w("here. A first draft of this audit asserted they were figure/table/tool")
w("items plus collisions; that was an inference presented as a measurement")
w("and has been removed.")
w()
w("What the release *does* record, for the 580 rows that are present:")
w()
w("| collision_status | n |")
w("|---|---:|")
for k, v in sb.collision_status.value_counts().items():
    w(f"| {k} | {v} |")
w()
w("Note the 6 `conflicting_source_id_disambiguated` rows are **not** the same")
w("6 rows that lack the text-only slice — they are disjoint sets, so the two")
w("subtractions below are independent, not the same six items counted twice.")
w()
w("To establish the 112 one would have to diff the upstream SciBench release")
w("against this table. That is tracked as a P2 item; it does not affect any")
w("denominator this paper reports, because the paper's denominator is the 574")
w("it actually ran.")
w()
w("### Where the 580 - 574 = 6 go")
w()
out = sb[~has_slice]
w(f"{len(out)} released rows lack the `text_only` slice and are therefore")
w("outside the matched denominator:")
w()
w("| problem_uid | slices |")
w("|---|---|")
for _, r in out.iterrows():
    w(f"| `{r.problem_uid}` | {r.available_slices_json} |")
w()
w("**`574 matched` is not `574 total benchmark`.** The upstream benchmark has")
w("692 items; 580 reach the release; 574 carry the text-only slice this")
w("project's protocol can run. All 574 were run — no sub-sampling.")
w()
w(f"- license: {sb.source_license_id.unique().tolist()}")
w(f"- training policy: {sb.training_use_policy.unique().tolist()}")
w()

open(os.path.join(OUT, "SAMPLING_AUDIT.md"), "w").write("\n".join(L) + "\n")
print(f"\nwrote {OUT}/SAMPLING_AUDIT.md")

# ---------------------------------------------------------------- figure
try:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig, ax = plt.subplots(1, 2, figsize=(7.0, 2.6))
    b = np.histogram_bin_edges(full, bins=20)
    ax[0].hist(full, bins=b, density=True, alpha=.55, label=f"full pool (n={len(om)})")
    ax[0].hist(sel, bins=b, density=True, alpha=.55, label=f"selected (n=1600)")
    ax[0].set_xlabel("difficulty_score"); ax[0].set_ylabel("density")
    ax[0].legend(fontsize=7); ax[0].set_title("OmniMath2 difficulty", fontsize=9)
    ks_f = np.sort(full); ks_s = np.sort(sel)
    ax[1].plot(ks_f, np.linspace(0, 1, len(ks_f)), label="full pool")
    ax[1].plot(ks_s, np.linspace(0, 1, len(ks_s)), "--", label="selected")
    ax[1].set_xlabel("difficulty_score"); ax[1].set_ylabel("cumulative")
    ax[1].legend(fontsize=7); ax[1].set_title("empirical CDF", fontsize=9)
    fig.tight_layout()
    p = os.path.join(ROOT, "figures", "audit_sampling_representativeness.png")
    fig.savefig(p, dpi=200); print("wrote", p)
except Exception as e:
    print("figure skipped:", type(e).__name__, e)
